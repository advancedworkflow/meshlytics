import { describe, expect, it } from "vitest";
import type { InstrumentationPlan } from "@meshlytics/schema";
import { generateInstrumentationModule } from "./generate.js";

const plan: InstrumentationPlan = {
  version: 1,
  generatedAt: "2026-09-06T12:00:00.000Z",
  application: {
    framework: "next",
    router: "app",
    typescript: true,
    rootDir: "/app",
    routes: [{ path: "/", file: "page.tsx", dynamicSegments: [] }],
  },
  tracked: [
    {
      route: { path: "/", file: "page.tsx", dynamicSegments: [] },
      params: { routeParams: true, queryParams: false, utmParams: true, referrer: true },
    },
    {
      route: { path: "/checkout", file: "checkout/page.tsx", dynamicSegments: [] },
      params: { routeParams: false, queryParams: true, utmParams: false, referrer: false },
    },
  ],
};

describe("generateInstrumentationModule", () => {
  const output = generateInstrumentationModule(plan);

  it("only imports the plan type, so it adds nothing to the bundle", () => {
    expect(output).toContain('import type { MeshlyticsPlan } from "meshlytics";');
    expect(output).not.toMatch(/^import \{/m);
  });

  it("exports the plan without creating a client, leaving endpoint/storage to the app", () => {
    expect(output).toContain("export const meshlyticsPlan: MeshlyticsPlan = {");
    // createClient only appears in the usage comment.
    expect(output).not.toMatch(/^(?!\/\/).*createClient\(/m);
  });

  it("is valid code that evaluates to the plan", () => {
    const body = output
      .replace(/^import type .*$/m, "")
      .replace("export const meshlyticsPlan: MeshlyticsPlan =", "return");
    const evaluated = new Function(body)();
    expect(evaluated.routes.map((r: { path: string }) => r.path)).toEqual(["/", "/checkout"]);
    expect(evaluated.excludedRoutes).toEqual([]);
  });

  it("includes every tracked route's path", () => {
    expect(output).toContain('path: "/",');
    expect(output).toContain('path: "/checkout",');
  });

  it("renders each route's own parameter config, not a shared default", () => {
    expect(output).toMatch(/path: "\/",\s*params: \{\s*routeParams: true,\s*queryParams: false,\s*utmParams: true,\s*referrer: true,/);
    expect(output).toMatch(/path: "\/checkout",\s*params: \{\s*routeParams: false,\s*queryParams: true,\s*utmParams: false,\s*referrer: false,/);
  });

  it("carries the plan version, generatedAt, and application metadata", () => {
    expect(output).toContain("version: 1,");
    expect(output).toContain('generatedAt: "2026-09-06T12:00:00.000Z",');
    expect(output).toContain('framework: "next",');
    expect(output).toContain('router: "app",');
  });

  it("leads with a generated-file warning comment", () => {
    expect(output.startsWith("// This file is generated by `meshlytics instrument`.")).toBe(true);
  });

  it("lists discovered-but-untracked routes as excludedRoutes, and only those", () => {
    const output = generateInstrumentationModule({
      ...plan,
      application: {
        ...plan.application,
        routes: [
          { path: "/", file: "page.tsx", dynamicSegments: [] },
          { path: "/projects/[id]", file: "projects/[id]/page.tsx", dynamicSegments: ["id"] },
          { path: "/projects/new", file: "projects/new/page.tsx", dynamicSegments: [] },
        ],
      },
      tracked: [
        {
          route: { path: "/projects/[id]", file: "projects/[id]/page.tsx", dynamicSegments: ["id"] },
          params: { routeParams: true, queryParams: false, utmParams: true, referrer: true },
        },
      ],
    });

    expect(output).toContain('excludedRoutes: [\n    "/",\n    "/projects/new",\n  ],');
  });

  it("produces an empty excludedRoutes array when every route is tracked", () => {
    expect(output).toContain("excludedRoutes: [],");
  });

  it("produces an empty routes array when nothing is tracked", () => {
    const empty = generateInstrumentationModule({ ...plan, tracked: [] });
    expect(empty).toContain("routes: [],");
  });
});
